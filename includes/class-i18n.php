final class I18n {
	/**
	 * Register locale filters before any plugin strings are rendered.
	 *
	 * @return void
	 */
	public static function register(): void {
		add_filter( 'gettext_mrn-form', array( self::class, 'translate' ), 10, 3 );
	}

	/**
	 * Translate a Persian source string for English WordPress locales.
	 *
	 * @param string $translation Current translation.
	 * @param string $text Original text.
	 * @param string $domain Text domain.
	 * @return string
	 */
	public static function translate( string $translation, string $text, string $domain ): string {
		if ( 'mrn-form' !== $domain || ! self::is_english() ) {
			return $translation;
		}

		return self::english()[ $text ] ?? $translation;
	}

	/**
	 * Determine whether the active request locale is English.
	 *
	 * @return bool
	 */
	private static function is_english(): bool {
		$locale = strtolower( str_replace( '-', '_', determine_locale() ) );
		return 'en' === $locale || str_starts_with( $locale, 'en_' );
	}

